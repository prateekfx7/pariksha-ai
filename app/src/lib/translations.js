// Auto-fill all remaining scheduled Indian languages so EVERY language code has valid dictionary keys!
const BASE_DICT = translations['hi'];
const SCHEDULED_LANG_CODES = ['mr', 'ta', 'gu', 'ur', 'kn', 'or', 'ml', 'pa', 'as', 'mai', 'sat', 'ks', 'ne', 'kok', 'sd', 'doi', 'mni', 'brx', 'sa'];

SCHEDULED_LANG_CODES.forEach(code => {
  if (!translations[code]) {
    translations[code] = { ...BASE_DICT };
  } else {
    // Fill in any missing keys from Base Dictionary
    Object.keys(translations['en']).forEach(k => {
      if (!translations[code][k]) {
        translations[code][k] = translations['hi'][k] || translations['en'][k];
      }
    });
  }
});

// Translation Resolver Function
export function getTranslation(langCode, key, fallback = '') {
  const current = translations[langCode];
  if (current && current[key]) {
    return current[key];
  }
  const hindi = translations['hi'];
  if (hindi && hindi[key]) {
    return hindi[key];
  }
  const english = translations['en'];
  if (english && english[key]) {
    return english[key];
  }
  return fallback || key;
}

// Helper to translate statistical skill competency names
export function translateSkill(skillName, langCode) {
  if (SKILL_TRANSLATIONS[skillName]) {
    const langMap = SKILL_TRANSLATIONS[skillName];
    return langMap[langCode] || langMap['hi'] || langMap['en'] || skillName;
  }
  return skillName;
}
