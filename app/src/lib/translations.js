// Fallback generator for remaining scheduled languages so that any language code works gracefully
export function getTranslation(langCode, key, fallback = '') {
  const langObj = translations[langCode] || translations['hi'] || translations['en'];
  if (langObj && langObj[key]) {
    return langObj[key];
  }
  // fallback to English
  if (translations['en'] && translations['en'][key]) {
    return translations['en'][key];
  }
  return fallback || key;
}
